INSERT INTO event_session_publication (event_id, session_id, start_time, end_time)
SELECT session.event_id, session.id, session.start_time, session.end_time
FROM event_session_catalog session
JOIN event_publication publication ON publication.event_id = session.event_id
WHERE NOT EXISTS (
    SELECT 1 FROM event_session_publication snapshot
    WHERE snapshot.event_id = session.event_id AND snapshot.session_id = session.id
);

INSERT INTO ticket_category_publication
    (event_id, session_id, ticket_category_id, name, price_cents)
SELECT session.event_id, ticket.session_id, ticket.id, ticket.name, ticket.price_cents
FROM ticket_category_catalog ticket
JOIN event_session_catalog session ON session.id = ticket.session_id
JOIN event_publication publication ON publication.event_id = session.event_id
WHERE NOT EXISTS (
    SELECT 1 FROM ticket_category_publication snapshot
    WHERE snapshot.event_id = session.event_id
      AND snapshot.session_id = ticket.session_id
      AND snapshot.ticket_category_id = ticket.id
);

INSERT INTO event_rule_publication
    (event_id, rule_group, rule_code, title, content, display_order)
SELECT rule.event_id, rule.rule_group, rule.rule_code, rule.title, rule.content, rule.display_order
FROM event_rule_catalog rule
JOIN event_publication publication ON publication.event_id = rule.event_id
WHERE NOT EXISTS (
    SELECT 1 FROM event_rule_publication snapshot
    WHERE snapshot.event_id = rule.event_id AND snapshot.rule_code = rule.rule_code
);

INSERT INTO event_detail_section_publication
    (event_id, section_id, section_type, title, content, image_url, display_order)
SELECT section.event_id, section.id, section.section_type, section.title,
       section.content, section.image_url, section.display_order
FROM event_detail_section_catalog section
JOIN event_publication publication ON publication.event_id = section.event_id
WHERE NOT EXISTS (
    SELECT 1 FROM event_detail_section_publication snapshot
    WHERE snapshot.event_id = section.event_id AND snapshot.section_id = section.id
);

