ALTER TABLE ticket_order ADD COLUMN IF NOT EXISTS passenger_document_last4 VARCHAR(4) NOT NULL DEFAULT '0000';
ALTER TABLE ticket_order ADD COLUMN IF NOT EXISTS active_grab_key VARCHAR(96) NULL;
ALTER TABLE ticket_order ADD COLUMN IF NOT EXISTS refund_time TIMESTAMP NULL;
UPDATE ticket_order
SET active_grab_key = CONCAT(user_id, ':', session_id, ':', ticket_category_id)
WHERE order_status IN ('PENDING_PAYMENT', 'PAID', 'PARTIALLY_REFUNDED') AND active_grab_key IS NULL;
UPDATE ticket_order
SET active_grab_key = NULL
WHERE order_status IN ('CANCELED', 'REFUNDED');
ALTER TABLE ticket_order ADD CONSTRAINT IF NOT EXISTS uk_ticket_order_active UNIQUE (active_grab_key);

CREATE TABLE IF NOT EXISTS ticket_order_passenger (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    passenger_sequence INT NOT NULL,
    passenger_name VARCHAR(64) NOT NULL,
    passenger_document_type VARCHAR(32) NOT NULL,
    passenger_document_last4 VARCHAR(4) NOT NULL,
    CONSTRAINT uk_ticket_order_passenger_sequence UNIQUE (order_id, passenger_sequence)
);

INSERT INTO ticket_order_passenger
    (order_id, passenger_sequence, passenger_name, passenger_document_type, passenger_document_last4)
SELECT ticket_order.id, 1, ticket_order.passenger_name,
       ticket_order.passenger_document_type, ticket_order.passenger_document_last4
FROM ticket_order
WHERE NOT EXISTS (
    SELECT 1
    FROM ticket_order_passenger
    WHERE ticket_order_passenger.order_id = ticket_order.id
);

